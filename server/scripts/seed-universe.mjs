// ── Schema (minimal — just enough for upsert) ───────────────────────────────
const stockSchema = new mongoose.Schema({
  symbol:        { type: String, required: true, unique: true, uppercase: true },
  companyName:   String,
  sector:        { type: String, default: 'Unknown' },
  industry:      String,
  indices:       { type: [String], default: [] },
  marketCapTier: { type: String, default: '' },
  active:        { type: Boolean, default: true },
  inUniverse:    { type: Boolean, default: true },
}, { strict: false, timestamps: true });

const Stock = mongoose.models.Stock || mongoose.model('Stock', stockSchema);

// ── Main ─────────────────────────────────────────────────────────────────────
async function main() {
  await mongoose.connect(MONGO_URI);
  console.log(`Connected to MongoDB: ${MONGO_URI.replace(/\/\/[^@]+@/, '//***:***@')}`);

  // Deduplicate the list by symbol (in case of duplicates in the array above)
  const seen = new Set();
  const unique = STOCKS.filter(([sym]) => {
    if (seen.has(sym)) return false;
    seen.add(sym);
    return true;
  });

  let upserted = 0;
  for (const [symbol, companyName, sector, indices, marketCapTier] of unique) {
    await Stock.findOneAndUpdate(
      { symbol },
      { $setOnInsert: { active: true, inUniverse: true }, $set: { companyName, sector, indices, marketCapTier } },
      { upsert: true, new: true }
    );
    upserted++;
    if (upserted % 50 === 0) console.log(`  … ${upserted} stocks upserted`);
  }

  console.log(`\nDone: ${upserted} stocks in universe.`);
  await mongoose.disconnect();
}

main().catch((err) => { console.error(err); process.exit(1); });
